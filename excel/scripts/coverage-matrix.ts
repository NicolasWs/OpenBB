/**
 * NIC-70: write docs/coverage-matrix.json and docs/coverage-matrix.md, classifying every
 * endpoint of an openbb-api server by how its data lands in Excel.
 *
 *   npx tsx scripts/coverage-matrix.ts --openapi fixtures/openapi.json
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { buildCatalog, type OpenApiDoc } from "../src/catalog/build";
import type { CatalogEntry } from "../src/catalog/types";

function arg(name: string, fallback: string): string {
  const index = process.argv.indexOf(`--${name}`);
  return index >= 0 && process.argv[index + 1] ? process.argv[index + 1] : fallback;
}

const openapiPath = arg("openapi", "fixtures/openapi.json");
const outDir = arg("out", "docs");
const doc = JSON.parse(readFileSync(openapiPath, "utf8")) as OpenApiDoc;
const providersPath = join(dirname(openapiPath), "providers.json");
const knownProviders = existsSync(providersPath)
  ? Object.keys(JSON.parse(readFileSync(providersPath, "utf8")) as Record<string, unknown>)
  : undefined;
const catalog = buildCatalog(doc, { source: openapiPath, knownProviders });

const rows = catalog.entries.map((entry) => ({
  route: entry.route,
  method: entry.method,
  category: entry.category,
  providers: entry.providers,
  required_params: entry.params.filter((p) => p.required).map((p) => p.name),
  shape: entry.shape,
  landing: entry.landing,
  needs_key: entry.needsKey,
  typed_function: entry.typed ? `OBB.${entry.functionId}` : null,
}));
writeFileSync(`${outDir}/coverage-matrix.json`, `${JSON.stringify(rows, null, 1)}\n`);

function countBy<T extends string>(items: CatalogEntry[], key: (entry: CatalogEntry) => T): Map<T, number> {
  const counts = new Map<T, number>();
  for (const item of items) counts.set(key(item), (counts.get(key(item)) ?? 0) + 1);
  return new Map([...counts.entries()].sort((a, b) => b[1] - a[1]));
}

const entries = catalog.entries;
const landings = ["spill", "single-cell", "file", "chart", "range-input", "none"] as const;
const byCategory = new Map<string, CatalogEntry[]>();
for (const entry of entries) {
  byCategory.set(entry.category, [...(byCategory.get(entry.category) ?? []), entry]);
}

const lines: string[] = [];
lines.push("# Coverage matrix: how each openbb-api endpoint lands in Excel");
lines.push("");
lines.push(
  `Generated by \`npm run matrix\` from \`${openapiPath}\`, recorded from the nicogeek server ` +
    "(openbb-core 2.0.1). The machine-readable version is `coverage-matrix.json` (one row per endpoint).",
);
lines.push("");
lines.push(
  `**${entries.length} endpoints**, of which ${entries.filter((e) => e.landing === "spill" || e.landing === "single-cell").length} ` +
    `land directly in cells, and ${entries.filter((e) => e.typed).length} get a typed \`=OBB.<ROUTE>()\` function ` +
    "(standard routers). Every cell-landing endpoint is also reachable through `=OBB.QUERY()`.",
);
lines.push("");
lines.push("## By shape");
lines.push("");
lines.push("| Shape | Endpoints | Lands as | Meaning |");
lines.push("|---|---:|---|---|");
const meaning: Record<string, string> = {
  table: "list of records with declared columns",
  "table-dynamic": "list of records whose columns are known only at runtime (e.g. Fed `pivot_wide` tables)",
  record: "one object, spilled as key/value rows",
  columnar: "parallel lists (e.g. options chains), zipped into rows",
  nested: "records with object or list fields, flattened to `a.b` columns or JSON text",
  document: "text, markdown or HTML, in one cell (truncated at 32,767 chars) or as a file",
  file: "downloads and document viewers, saved from the task pane (M2)",
  chart: "chart-only routes returning Plotly JSON (M2)",
  scalar: "one number or string in one cell",
  "range-input": "POST analytics taking a data range as input (not yet in Linear)",
  helper: "parameter option lists used by the task pane, not data",
};
for (const [shape, count] of countBy(entries, (e) => e.shape)) {
  const landing = entries.find((e) => e.shape === shape)?.landing ?? "";
  lines.push(`| \`${shape}\` | ${count} | ${landing} | ${meaning[shape] ?? ""} |`);
}
lines.push("");
lines.push("## By category");
lines.push("");
lines.push(`| Category | Endpoints | ${landings.join(" | ")} | Needs key |`);
lines.push(`|---|---:|${landings.map(() => "---:").join("|")}|---|`);
for (const [category, items] of [...byCategory.entries()].sort((a, b) => b[1].length - a[1].length)) {
  const keyed = [...new Set(items.flatMap((e) => e.needsKey))].join(", ");
  const cells = landings.map((landing) => items.filter((e) => e.landing === landing).length || "");
  lines.push(`| ${category} | ${items.length} | ${cells.join(" | ")} | ${keyed} |`);
}
lines.push("");
lines.push("## Exceptions: endpoints that do not spill into cells");
lines.push("");
for (const landing of ["single-cell", "file", "chart", "range-input"] as const) {
  const items = entries.filter((e) => e.landing === landing);
  lines.push(`### ${landing} (${items.length})`);
  lines.push("");
  lines.push(items.map((e) => `\`${e.method} ${e.route}\``).join(", "));
  lines.push("");
}
lines.push("## Known runtime gaps on the recorded server");
lines.push("");
lines.push("- `GET coverage/command_model` returns 422 (server bug), so the catalog is built from `openapi.json`.");
lines.push("- nasdaq historical prices (equity, ETF) return 204 for every request; cboe historical works.");
lines.push("- Keyed providers (fred, bls, eia, cftc, congress_gov) return 400 \"Missing credential\" until keys are set on the server.");
lines.push("");
writeFileSync(`${outDir}/coverage-matrix.md`, lines.join("\n"));
console.log(`Wrote ${rows.length} rows to ${outDir}/coverage-matrix.{json,md}`);
